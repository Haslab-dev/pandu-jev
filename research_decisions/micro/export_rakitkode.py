"""Export Micro Model Weights to pure Go bytes and JSON."""

import json
from pathlib import Path
from typing import Dict, Any, Tuple

DEFAULT_GO_TARGET = Path(__file__).resolve().parent.parent.parent.parent / "rakitkode" / "decisions" / "weights_generated.go"
DEFAULT_JSON_TARGET = Path(__file__).resolve().parent.parent.parent.parent / "rakitkode" / "decisions" / "model_weights.json"


def export_to_rakitkode(
    weights_dict: Dict[str, Any],
    go_path: Path = DEFAULT_GO_TARGET,
    json_path: Path = DEFAULT_JSON_TARGET,
) -> Tuple[str, str]:
    """Generate both JSON weights file and pure Go byte-embed source file."""
    # Write JSON
    if json_path.parent.exists():
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(weights_dict, f, indent=2)

    # Write Go embed source
    json_bytes = json.dumps(weights_dict).encode("utf-8")

    go_code = f"""// Code generated by pandu-jev/research_decisions/micro/export_rakitkode.py. DO NOT EDIT.

package decisions

// embeddedWeightsRaw contains the pre-compiled, RLCD-trained small neural model weights.
// Stored as an in-memory byte slice to ensure 100% offline, zero-disk-dependency operation.
var embeddedWeightsRaw = []byte({format_go_byte_slice(json_bytes)})
"""
    if go_path.parent.exists():
        with open(go_path, "w", encoding="utf-8") as f:
            f.write(go_code)

    return str(go_path), str(json_path)


def format_go_byte_slice(b: bytes, line_width: int = 120) -> str:
    lines = ["\n\t\""]
    curr_len = 2
    for byte in b:
        hex_esc = f"\\x{byte:02x}"
        if curr_len + len(hex_esc) > line_width:
            lines.append("\"\n\t+ \"")
            curr_len = 5
        lines.append(hex_esc)
        curr_len += len(hex_esc)
    lines.append("\"")
    return "".join(lines)
