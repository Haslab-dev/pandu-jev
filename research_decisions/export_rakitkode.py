"""Export utilities for compiling Python decision models directly into RakitKode Go code.

Generates:
1. rakitkode/decisions/weights_generated.go (Compile-time embedded Go arrays)
2. rakitkode/decisions/model_weights.json (Portable JSON format)
"""

import json
import os
from pathlib import Path
from typing import Dict, Any, List, Tuple
import numpy as np


def export_to_rakitkode(
    weights_data: Dict[str, Any],
    rakitkode_root: str = None,
) -> Tuple[str, str]:
    """Write weights to rakitkode/decisions/weights_generated.go and model_weights.json."""
    if rakitkode_root is None:
        # Default relative to pandu-jev
        base = Path(__file__).resolve().parent.parent.parent / "rakitkode"
    else:
        base = Path(rakitkode_root)

    decisions_dir = base / "decisions"
    decisions_dir.mkdir(parents=True, exist_ok=True)

    json_path = decisions_dir / "model_weights.json"
    go_path = decisions_dir / "weights_generated.go"

    # 1. Write JSON
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(weights_data, f, indent=2)

    # 2. Write Go Source
    w1 = np.array(weights_data["W1"])
    b1 = np.array(weights_data["b1"])
    w_cat = np.array(weights_data["W_cat"])
    b_cat = np.array(weights_data["b_cat"])
    w_tools = np.array(weights_data["W_tools"])
    b_tools = np.array(weights_data["b_tools"])
    w_role = np.array(weights_data["W_role"])
    b_role = np.array(weights_data["b_role"])
    w_risk = np.array(weights_data["W_risk"])
    b_risk = np.array(weights_data["b_risk"])
    w_del = np.array(weights_data["W_delegate"])
    b_del = np.array(weights_data["b_delegate"])

    def format_slice_2d(mat: np.ndarray) -> str:
        rows = []
        for row in mat:
            vals = ", ".join(f"{v:.7f}" for v in row)
            rows.append(f"\t\t{{{vals}}}")
        return "{\n" + ",\n".join(rows) + ",\n\t}"

    def format_slice_1d(vec: np.ndarray) -> str:
        vals = ", ".join(f"{v:.7f}" for v in vec)
        return f"{{{vals}}}"

    vocab_str = ", ".join(f'"{w}"' for w in weights_data["vocabulary"])
    cats_str = ", ".join(f'"{c}"' for c in weights_data["categories"])
    roles_str = ", ".join(f'"{r}"' for r in weights_data["roles"])
    risks_str = ", ".join(f'"{k}"' for k in weights_data["risk_levels"])

    code = f"""// Code generated by pandu-jev/research_decisions/export_rakitkode.py; DO NOT EDIT.
package decisions

const (
\tSmallModelInputDim     = {w1.shape[1]}
\tSmallModelHiddenDim    = {w1.shape[0]}
\tSmallModelNumCats      = {len(weights_data["categories"])}
\tSmallModelNumRoles     = {len(weights_data["roles"])}
\tSmallModelNumRisks     = {len(weights_data["risk_levels"])}
\tSmallModelTemperature  = {weights_data["temperature"]:.3f}
\tSmallModelVersion      = "{weights_data.get("version", "small-rlcd-v2")}"
)

var defaultVocabulary = []string{{
\t{vocab_str},
}}

var defaultCategories = []string{{
\t{cats_str},
}}

var defaultRoles = []string{{
\t{roles_str},
}}

var defaultRisks = []string{{
\t{risks_str},
}}

var weightsB1 = [{w1.shape[0]}]float32{format_slice_1d(b1)}

var weightsW1 = [{w1.shape[0]}][{w1.shape[1]}]float32{format_slice_2d(w1)}

var weightsBCat = [{w_cat.shape[0]}]float32{format_slice_1d(b_cat)}

var weightsWCat = [{w_cat.shape[0]}][{w_cat.shape[1]}]float32{format_slice_2d(w_cat)}

var weightsBTools = [{w_tools.shape[0]}]float32{format_slice_1d(b_tools.flatten())}

var weightsWTools = [{w_tools.shape[0]}][{w_tools.shape[1]}]float32{format_slice_2d(w_tools)}

var weightsBRole = [{w_role.shape[0]}]float32{format_slice_1d(b_role)}

var weightsWRole = [{w_role.shape[0]}][{w_role.shape[1]}]float32{format_slice_2d(w_role)}

var weightsBRisk = [{w_risk.shape[0]}]float32{format_slice_1d(b_risk)}

var weightsWRisk = [{w_risk.shape[0]}][{w_risk.shape[1]}]float32{format_slice_2d(w_risk)}

var weightsBDelegate = [{w_del.shape[0]}]float32{format_slice_1d(b_del.flatten())}

var weightsWDelegate = [{w_del.shape[0]}][{w_del.shape[1]}]float32{format_slice_2d(w_del)}
"""

    with open(go_path, "w", encoding="utf-8") as f:
        f.write(code)

    return str(go_path), str(json_path)
